def build_lookup(translations):
    return {normalize_key(key): value for key, value in translations.items()}


def build_plural_lookup(plurals):
    return {
        (normalize_key(singular), normalize_key(plural)): values
        for (singular, plural), values in plurals.items()
    }


def fill_po(path, translations, plural_translations, language_name):
    if not path.exists():
        raise FileNotFoundError(f"Missing file: {path}")

    po = polib.pofile(str(path))

    lookup = build_lookup(translations)
    plural_lookup = build_plural_lookup(plural_translations)

    filled = 0
    filled_plurals = 0
    still_empty = 0

    for entry in po:
        if entry.obsolete:
            continue

        if entry.msgid == "":
            continue

        if entry.msgid_plural:
            key = (normalize_key(entry.msgid), normalize_key(entry.msgid_plural))

            if key in plural_lookup:
                values = plural_lookup[key]

                for index in range(len(entry.msgstr_plural)):
                    if index < len(values):
                        entry.msgstr_plural[index] = values[index]
                    else:
                        entry.msgstr_plural[index] = values[-1]

                if "fuzzy" in entry.flags:
                    entry.flags.remove("fuzzy")

                filled_plurals += 1
            else:
                if not any(value.strip() for value in entry.msgstr_plural.values()):
                    still_empty += 1

            continue

        key = normalize_key(entry.msgid)

        if key in lookup:
            entry.msgstr = lookup[key]

            if "fuzzy" in entry.flags:
                entry.flags.remove("fuzzy")

            filled += 1
        elif not entry.msgstr.strip():
            still_empty += 1

    po.save(str(path))

    print(f"{language_name}:")
    print(f"  Singular filled: {filled}")
    print(f"  Plural filled:   {filled_plurals}")
    print(f"  Still empty:     {still_empty}")
    print(f"  File:            {path}")
    print()


